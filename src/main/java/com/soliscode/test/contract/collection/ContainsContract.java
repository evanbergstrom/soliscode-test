package com.soliscode.test.contract.collection;

import java.util.Collection;
import java.util.List;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import com.soliscode.test.contract.support.CollectionContractSupport;
import com.soliscode.test.util.CollectionTestUtils;
import com.soliscode.test.util.MatchNothing;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;


/// The `ContainsContract` interface defines a contract for testing the behavior of
/// the [Collection#contains(Object)] method. It is designed for use with collections
/// that conform to the `Collection` interface and supports various test cases to
/// evaluate the correctness of the `contains()` method implementation.
/// `ContainsContract` provides tests the check the following:
///
///   - Verifying `contains()` behavior when performed on empty collections.
///   - Testing `contains()` behavior on collections with elements.
///   - Checking the compatibility of `contains()` with `null` values.
///   - Validating the behavior of `contains()` when passed incompatible types.
///   - Ensuring appropriate exceptions are thrown for unsupported operations.
///
/// The test methods defined in this interface are written using JUnit 6 and utilize default
/// method implementations to allow seamless integration into concrete test suites. The tests are
/// only executed when the respective operation is supported by the collection, as determined by
/// the [#supportsMethod] method. The objectProvider methods [#provider()] and
/// [#elementProvider()] are utilized to create collection instances and test elements.
///
/// @param <E> the type of elements contained in the collection.
/// @param <C> the type of the collection being tested, which extends [Collection].
///
/// @see Collection#contains(Object)
/// @see CollectionContractSupport
public interface ContainsContract<C extends Collection<E>, E> extends CollectionContractSupport<C, E> {


    /// Verifies the behavior of the [Collection#contains(Object)] method when invoked on an empty collection.
    ///
    /// This test ensures that for every element generated by the [#elementProvider()],
    /// the `contains()` method returns `false` when called on an empty collection.
    /// The method's correctness is assessed in the absence of pre-existing elements in the collection.
    ///
    /// Implementation Details:
    ///   - An empty collection instance is created using [#provider()#emptyInstance()].
    ///   - A set of unique instances is generated via
    ///     [com.soliscode.test.provider.ObjectProvider#createUniqueInstances(int)].
    ///   - Assertions verify that `collection.contains(e)` returns `false` for all elements `e`.
    ///
    /// This test is only executed if [#supportsMethod(com.soliscode.test.InterfaceMethod)] returns `true`
    /// for [CollectionMethods#CONTAINS], indicating that the collection supports the `contains()` method.
    ///
    /// Example Scenario:
    ///   - An empty collection is created.
    ///   - Random elements not in the collection are checked with `contains()`.
    ///   - Result: `false` is returned for all checks.
    ///
    /// @throws org.opentest4j.AssertionFailedError if any assertion fails.
    /// @see Collection#contains(Object)
    /// @see CollectionMethods#CONTAINS
    @DisplayName("contains(Object) returns false for an empty collection")
    @Test
    default void containsWhenEmptyReturnsFalse() {
        if (supportsMethod(CollectionMethods.CONTAINS)) {
            Collection<E> collection = provider().emptyInstance();
            List<E> values = elementProvider().createUniqueInstances(DEFAULT_SIZE);
            for (final E e : values) {
                assertFalse(collection.contains(e));
            }
        }
    }


    /// Verifies the behavior of the [Collection#contains(Object)] method when invoked on a
    /// non-empty collection.
    ///
    /// This test ensures that:
    ///     - For every element added to the collection, `contains()` returns `true`.
    ///     - For every element not added to the collection, `contains()` returns `false`.
    ///
    /// Implementation Details:
    ///     - A collection is created using the elements from the first half of a list of
    ///     unique instances provided by [#elementProvider()].
    ///     - Assertions are performed to verify that the added elements are recognized by
    ///     `contains()`.
    ///     - Assertions are performed to verify that elements not in the collection return `false`.
    ///
    /// This test is only executed if [#supportsMethod(com.soliscode.test.InterfaceMethod)] returns `true`
    /// for [CollectionMethods#CONTAINS].
    ///
    /// @throws org.opentest4j.AssertionFailedError if any assertion fails.
    /// @see Collection#contains(Object)
    /// @see CollectionMethods#CONTAINS
    @DisplayName("contains(Object) returns expected results for a collection with elements")
    @Test
    default void containsWhenNotEmptyReturnsExpectedResults() {
        if (supportsMethod(CollectionMethods.CONTAINS)) {
            List<E> values = elementProvider().createUniqueInstances(DEFAULT_SIZE);
            int middle = values.size() / 2;
            List<E> contained = values.subList(0, middle);
            List<E> notContained = values.subList(middle, values.size());
            Collection<E> collection = provider().createInstance(contained);

            for (final E e : contained) {
                assertTrue(collection.contains(e));
            }

            for (final E e : notContained) {
                assertFalse(collection.contains(e));
            }
        }
    }


    /// Tests that the [Collection#contains(Object)] method behaves correctly for collections
    /// that may include `null` values.
    ///
    /// This test verifies that:
    /// 1. If the collection permits null elements, the method:
    ///    - Handles `null` as a valid input.
    ///    - Returns `true` for `null` if the collection contains it.
    /// 2. If the collection does not permit null elements, the method:
    ///    - Throws a [NullPointerException] when invoked with `null` as an argument, or returns `false`:
    ///      [Collection#contains(Object)] makes the exception optional.
    ///
    /// This test is only executed if [#supportsMethod(com.soliscode.test.InterfaceMethod)] returns `true`
    /// for `CollectionMethods.CONTAINS`, indicating that the collection supports the `contains` method.
    /// Example scenarios covered:
    /// - A collection containing both elements and `null`, where the `contains()` method
    ///   correctly identifies `null` as an element.
    /// - A collection not supporting null values, where invoking `contains(null)`
    ///   throws a [NullPointerException] or returns `false`.
    ///
    /// @throws org.opentest4j.AssertionFailedError If any of the assertions fail.
    /// @see Collection#contains(Object)
    /// @see CollectionMethods#CONTAINS
    @DisplayName("contains(Object) works for a collection with null elements")
    @Test
    default void containsWithNullValueReturnsTrue() {
        if (supportsMethod(CollectionMethods.CONTAINS)) {
            if (permitNulls()) {
                List<E> values = elementProvider().createUniqueInstances(2);
                List<E> elements = CollectionTestUtils.listOf(values.get(0), null, values.get(1));
                Collection<E> collection = provider().createInstance(elements);

                for (final E e : values) {
                    assertTrue(collection.contains(e));
                }
                assertTrue(collection.contains(null));
            } else {
                Collection<E> collection = provider().createInstance();
                assertResultOrNullPointer(false, () -> collection.contains(null), "contains(null)");
            }
        }
    }


    /// Tests that the [contains][Collection#contains] method behaves correctly when passed an incompatible type.
    ///
    /// This test verifies that:
    ///   - If the `permitIncompatibleTypes()` method returns `false`, the collection's
    ///     `contains()` method either throws a [ClassCastException] or returns `false` when invoked with an
    ///     incompatible type; [Collection#contains] makes the exception optional.
    ///   - If the `permitIncompatibleTypes()` method returns `true`, the collection's
    ///     `contains()` method returns `false` when invoked with an instance of an incompatible type.
    ///
    /// @see Collection#contains
    /// @see MatchNothing
    /// @throws org.opentest4j.AssertionFailedError If any of the assertions fail.
    @DisplayName("contains(Object) returns false for incompatible types")
    @Test
    default void containsWithIncompatibleTypeReturnsFalse() {
        if (supportsMethod(CollectionMethods.CONTAINS)) {
            if (permitIncompatibleTypes()) {
                Collection<E> collection = provider().createInstanceWithUniqueElements(2);
                assertFalse(collection.contains(new MatchNothing()));
            } else {
                // Collection#contains says the ClassCastException is optional: a collection that does not permit
                // incompatible types may throw it or return false (Collections.checkedList returns false).
                Collection<E> collection = provider().createInstanceWithUniqueElements(2);
                try {
                    assertFalse(collection.contains(new Object()));
                } catch (final ClassCastException expected) {
                    // permitted
                }
            }
        }
    }

    /// Verifies that the `Collection#contains(Object)` method throws an
    /// `UnsupportedOperationException` when the operation is not supported.
    ///
    /// This test ensures that:
    ///   - If the `supportsMethod(CollectionMethods.CONTAINS)` method returns `false`,
    ///     invoking `contains(Object)` on an empty collection instance results
    ///     in an `UnsupportedOperationException` being thrown.
    ///
    /// Implementation Details:
    ///     - An empty collection instance is created using `objectProvider().emptyInstance()`.
    ///     - The `contains(Object)` method is invoked with a sample object.
    ///     - Assertions verify that an `UnsupportedOperationException` is thrown.
    ///
    /// This test is executed only if the following conditions are met:
    ///     - `supportsMethod(CollectionMethods.CONTAINS)` returns `false`.
    ///
    /// Example Scenario:
    ///   - An empty collection that does not support the `contains(Object)` method
    ///     is created.
    ///   - The `contains(Object)` method is invoked with any object.
    ///   - Result: An `UnsupportedOperationException` is thrown.
    ///
    /// @throws org.opentest4j.AssertionFailedError If the collection does not throw
    ///         an `UnsupportedOperationException` when the `contains(Object)` method
    ///         is invoked and it is not supported.
    /// @throws UnsupportedOperationException If the `contains(Object)` method is invoked
    ///         on a collection that does not support it.
    ///
    /// @see Collection#contains(Object)
    /// @see CollectionMethods#CONTAINS
    @DisplayName("contains(Object) throws UnsupportedOperationException when not supported")
    @Test
    default void containsWhenNotSupportedThrowsUnsupportedOperationException() {
        if (!supportsMethod(CollectionMethods.CONTAINS)) {
            assertThrows(UnsupportedOperationException.class, () -> provider().emptyInstance().contains(new Object()));
        }
    }
}
